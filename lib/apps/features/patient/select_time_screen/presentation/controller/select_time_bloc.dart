import 'package:doctor_hunt/apps/core/data/appointment/repo/appointment_repository.dart';
import 'package:doctor_hunt/generated/translations.g.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import 'package:injectable/injectable.dart';

import '../../../../../core/data/session/user_session_manager.dart';
import '../../../appointments_tab/data/models/appointment/appointment.dart';
import '../../data/use_case/get_available_slots_use_case.dart';
import 'select_time_event.dart';
import 'select_time_state.dart';

@injectable
class SelectTimeBloc extends Bloc<SelectTimeEvent, SelectTimeState> {
  final GetAvailableSlotsUseCase _getAvailableSlotsUseCase;
  final UserSessionManager _userSessionManager;
  final AppointmentRepository _appointmentRepository;

  SelectTimeBloc(
    this._getAvailableSlotsUseCase,
    this._appointmentRepository,
    this._userSessionManager,
  ) : super(SelectTimeInitial()) {
    on<GetDoctorSlotsEvent>(_onGetDoctorSlots);
    on<BookAppointmentEvent>(_onBookAppointment);
  }

  Future<void> _onGetDoctorSlots(
    GetDoctorSlotsEvent event,
    Emitter<SelectTimeState> emit,
  ) async {
    emit(SelectTimeLoading());

    final result = await _getAvailableSlotsUseCase(
      doctorId: event.doctorId,
      availability: event.availability,
      startDate: event.startDate,
    );

    result.fold(
      (failure) => emit(SelectTimeError(failure.message)),
      (weeklyAvailability) => emit(SelectTimeLoaded(weeklyAvailability)),
    );
  }

  Future<void> _onBookAppointment(
    BookAppointmentEvent event,
    Emitter<SelectTimeState> emit,
  ) async {
    final currentState = state;
    if (currentState is! SelectTimeLoaded) return;

    emit(BookAppointmentLoading());

    final userOption = _userSessionManager.getCurrentUser();

    await userOption.fold(
      () async => emit(BookAppointmentError(t.errors.userNotLoggedIn)),
      (user) async {
        final appointment = Appointment(
          id: '',
          // Will be generated by Firestore
          patient: user,
          doctor: event.doctor,
          sessionTime: event.selectedTime,
          createdAt: DateTime.now(),
          fee: event.doctor.consultationFee,
          status: AppointmentStatus.upcoming,
        );

        final result = await _appointmentRepository.bookAppointment(
          appointment,
        );

        result.fold(
          (failure) => emit(BookAppointmentError(failure.message)),
          (_) => emit(BookAppointmentSuccess(event.selectedTime)),
        );
      },
    );

    // Re-emit loaded state so the UI goes back to the slots view
    // if booking failed or succeeded (dialog will handle success)
    emit(currentState);
  }
}
